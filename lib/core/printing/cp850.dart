/// Codificación **CP850** (página de códigos 850, "multilingüe latina").
///
/// Es la página que usan las impresoras térmicas ESC/POS para imprimir
/// castellano (`á é í ó ú ñ ¿ ¡`). El servidor codifica las plantillas con esa
/// misma página (`PrintEncoderService` → `codepage: cp850`), así que el encoder
/// local del corte de caja usa exactamente los mismos bytes.
class Cp850 {
  const Cp850._();

  /// Carácter de reemplazo cuando la impresora no tiene el glifo (`?`).
  static const int _unknown = 0x3F;

  /// Mitad alta de la tabla: `0x80`–`0xFF` → punto de código Unicode.
  static const List<int> _high = <int>[
    0x00C7, 0x00FC, 0x00E9, 0x00E2, 0x00E4, 0x00E0, 0x00E5, 0x00E7, // 0x80
    0x00EA, 0x00EB, 0x00E8, 0x00EF, 0x00EE, 0x00EC, 0x00C4, 0x00C5,
    0x00C9, 0x00E6, 0x00C6, 0x00F4, 0x00F6, 0x00F2, 0x00FB, 0x00F9, // 0x90
    0x00FF, 0x00D6, 0x00DC, 0x00F8, 0x00A3, 0x00D8, 0x00D7, 0x0192,
    0x00E1, 0x00ED, 0x00F3, 0x00FA, 0x00F1, 0x00D1, 0x00AA, 0x00BA, // 0xA0
    0x00BF, 0x00AE, 0x00AC, 0x00BD, 0x00BC, 0x00A1, 0x00AB, 0x00BB,
    0x2591, 0x2592, 0x2593, 0x2502, 0x2524, 0x00C1, 0x00C2, 0x00C0, // 0xB0
    0x00A9, 0x2563, 0x2551, 0x2557, 0x255D, 0x00A2, 0x00A5, 0x2510,
    0x2514, 0x2534, 0x252C, 0x251C, 0x2500, 0x253C, 0x00E3, 0x00C3, // 0xC0
    0x255A, 0x2554, 0x2569, 0x2566, 0x2560, 0x2550, 0x256C, 0x00A4,
    0x00F0, 0x00D0, 0x00CA, 0x00CB, 0x00C8, 0x0131, 0x00CD, 0x00CE, // 0xD0
    0x00CF, 0x2518, 0x250C, 0x2588, 0x2584, 0x00A6, 0x00CC, 0x2580,
    0x00D3, 0x00DF, 0x00D4, 0x00D2, 0x00F5, 0x00D5, 0x00B5, 0x00FE, // 0xE0
    0x00DE, 0x00DA, 0x00DB, 0x00D9, 0x00FD, 0x00DD, 0x00AF, 0x00B4,
    0x00AD, 0x00B1, 0x2017, 0x00BE, 0x00B6, 0x00A7, 0x00F7, 0x00B8, // 0xF0
    0x00B0, 0x00A8, 0x00B7, 0x00B9, 0x00B3, 0x00B2, 0x25A0, 0x00A0,
  ];

  /// Índice inverso (Unicode → byte), construido una sola vez.
  static final Map<int, int> _reverse = <int, int>{
    for (var index = 0; index < _high.length; index++) _high[index]: 0x80 + index,
  };

  /// Caracteres que el usuario escribe pero la impresora no tiene: se aproxima.
  static const Map<int, int> _approximations = <int, int>{
    0x2018: 0x27, // ‘
    0x2019: 0x27, // ’
    0x201C: 0x22, // “
    0x201D: 0x22, // ”
    0x2013: 0x2D, // –
    0x2014: 0x2D, // —
    0x2026: 0x2E, // …
    0x2022: 0xF9, // • (existe en CP850)
    0x20AC: 0x3F, // € (no existe en CP850)
    0xFEFF: 0x20,
  };

  /// Convierte el texto a bytes CP850 listos para la impresora.
  static List<int> encode(String text) {
    final bytes = <int>[];

    for (final rune in text.runes) {
      if (rune < 0x80) {
        bytes.add(rune);
        continue;
      }

      final mapped =
          _reverse[rune] ?? _approximations[rune] ?? _unknown;
      bytes.add(mapped);
    }

    return bytes;
  }
}
